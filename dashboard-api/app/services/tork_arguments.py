def get_system_arguments(system_code: str, segment: str = "general") -> Dict[str, Any]:
    """
    Returns arguments for a system code with fallback to T8 SmartOne.
    """
    code = (system_code or "T8").strip().upper()
    sys_data = TORK_SYSTEM_ARGUMENTS.get(code)
    
    # Fallback to closest system or T8
    if not sys_data:
        if "H" in code:
            sys_data = TORK_SYSTEM_ARGUMENTS["H1"]
        elif "S" in code:
            sys_data = TORK_SYSTEM_ARGUMENTS["S4"]
        elif "B" in code:
            sys_data = TORK_SYSTEM_ARGUMENTS["B1"]
        else:
            sys_data = TORK_SYSTEM_ARGUMENTS["T8"]

    seg_key = (segment or "general").lower()
    tagline = sys_data["taglines"].get(seg_key, sys_data["taglines"]["general"])

    return {
        "system_code": sys_data["system_code"],
        "system_name": sys_data["system_name"],
        "category": sys_data["category"],
        "default_sku": sys_data["default_sku"],
        "dispenser_title": sys_data["dispenser_title"],
        "tagline": tagline,
        "solution_summary": sys_data["solution_summary"],
        "arguments": sys_data["arguments"]
    }

